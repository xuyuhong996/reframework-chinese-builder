"""生成汉化核心包，并与同一官方 Nightly 的可选配套包一起发布。"""

import argparse
import hashlib
import json
import os
import re
import shutil
import tempfile
import tomllib
import zipfile
from dataclasses import dataclass
from pathlib import Path
from urllib.request import Request, urlopen

OFFICIAL_REPOSITORY = "praydog/REFramework-nightly"
API_BASE = "https://api.github.com"
API_VERSION = "2026-03-10"
CORE_NAME = "REFramework.zip"
COMPANION_NAMES = ("VR.zip", "csharp-api.zip")
MANIFEST_NAME = "build-info.json"
INSTRUCTIONS_NAME = "安装说明.txt"
BUNDLE_INFO_NAME = "bundle-info.json"
LAYOUT_MARKER = "Release layout: official-nightly"
UNIVERSAL_TARGET = "REFramework"
UNIVERSAL_DEFINITION = "REFRAMEWORK_UNIVERSAL"
REQUEST_TIMEOUT_SECONDS = 60
HASH_PREFIX_LENGTH = 12


@dataclass(frozen=True)
class CoreFiles:
    sourceRoot: Path
    dllPath: Path
    zipPath: Path
    qrPath: Path


def parseNightlyTag(tag):
    match = re.fullmatch(r"nightly-([0-9]{5})-([0-9a-f]{40})", tag)
    if match is None:
        raise ValueError("官方 Nightly 标签格式无效。")
    return match.groups()


def validateUniversalSource(sourceRoot):
    """同时核对声明和实际 CMake，不把单游戏 DLL 当成新版通用包。"""
    config = tomllib.loads((sourceRoot / "cmake.toml").read_text("utf-8"))
    cmake = (sourceRoot / "CMakeLists.txt").read_text("utf-8")
    for target in (UNIVERSAL_TARGET, "REFrameworkSDK"):
        definitions = config.get("target", {}).get(target, {}).get("compile-definitions", [])
        actual = re.search(rf"target_compile_definitions\(\s*{target}\s+PUBLIC\s+([^)]*)\)", cmake)
        if UNIVERSAL_DEFINITION not in definitions or actual is None:
            raise ValueError(f"{target} 缺少官方通用构建定义。")
        if UNIVERSAL_DEFINITION not in actual.group(1).split():
            raise ValueError(f"{target} 的实际 CMake 缺少通用编译标记。")
    if not re.search(r"add_library\(\s*REFramework\s+SHARED\s*\)", cmake):
        raise ValueError("未找到官方通用 DLL 目标。")
    readme = (sourceRoot / "README.md").read_text("utf-8")
    section = re.search(r"(?ms)^## Supported Games\s*\n(.*?)(?=^## |\Z)", readme)
    games = re.findall(r"(?m)^\s*[*-]\s+([^\r\n]+)", section.group(1)) if section else []
    if not games or len(games) != len(set(games)):
        raise ValueError("官方源码中的游戏清单无法识别或包含重复项。")
    return games


def createBuildInfo(files):
    games = validateUniversalSource(files.sourceRoot)
    versionText = (files.sourceRoot / "src/CommitHash.autogenerated").read_text("utf-8")
    sourceMatch = re.search(r'^#define REF_COMMIT_HASH "([0-9a-f]{40})"$', versionText, re.MULTILINE)
    if sourceMatch is None:
        raise ValueError("缺少实际编译源码的提交信息。")
    sourceSha = sourceMatch.group(1)
    tag = os.environ.get("UPSTREAM_RELEASE_TAG")
    if tag is not None and parseNightlyTag(tag)[1] != sourceSha:
        raise ValueError("Nightly 编号与实际源码提交不一致。")
    expectedSha = os.environ.get("UPSTREAM_SHA", sourceSha)
    if expectedSha != sourceSha:
        raise ValueError("实际源码与工作流固定的提交不一致。")
    return {
        "buildTarget": UNIVERSAL_TARGET,
        "upstreamReleaseTag": tag,
        "upstreamSourceSha": sourceSha,
        "officialReadmeGames": games,
        "dllSha256": hashlib.sha256(files.dllPath.read_bytes()).hexdigest(),
        "localizationScope": "REFramework 与词库已收录的 Mod 界面文字，不包括游戏剧情。",
        "verification": "构建和打包检查不代表已经逐游戏实测。",
    }


def renderInstructions(info):
    games = "\n".join(f"- {game}" for game in info["officialReadmeGames"])
    return (
        "REFramework 中文汉化成品\n\n"
        "普通使用：退出游戏，只把本包 dinput8.dll 放到游戏程序所在目录。\n"
        "同一个 DLL 使用官方运行时游戏识别，适用于本次官方版本支持的游戏。\n"
        "替换 DLL 时保留已有 reframework 脚本目录和配置。\n"
        "安装说明、构建信息和打赏图片无需复制到游戏目录。\n\n"
        "VR.zip：仅使用 VR 时安装配套文件，保留此汉化 DLL，遵循官方 VR 指引。\n"
        "csharp-api.zip：仅运行 C# 插件时安装，普通 Lua 脚本不需要。\n"
        "可选配套包均来自同一官方 Nightly，内容未做汉化修改。\n\n"
        "当前官方通用版本不支持 RE2、RE3、RE7 的非光追旧版。\n"
        f"{info['localizationScope']} 未收录的文字保留原文。\n"
        f"{info['verification']} 其他游戏的实际兼容性以对应官方版本为准。\n\n"
        f"官方源码 README 列出的游戏：\n{games}\n\n"
        f"官方标签：{info['upstreamReleaseTag'] or '手动构建，未固定 Nightly 标签'}\n"
        f"源码提交：{info['upstreamSourceSha']}\n"
        "官方项目：https://github.com/praydog/REFramework\n"
    )


def createCorePackage(files):
    # 在打开输出 ZIP 前核对所有输入，失败时保留已有成品。
    for requiredFile in (files.dllPath, files.qrPath, files.sourceRoot / "LICENSE"):
        if not requiredFile.is_file():
            raise ValueError(f"缺少打包文件：{requiredFile}")
    info = createBuildInfo(files)
    files.zipPath.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(files.zipPath, "w", zipfile.ZIP_DEFLATED) as package:
        package.write(files.dllPath, "dinput8.dll")
        package.write(files.qrPath, "赏口饭吃.jpg")
        package.write(files.sourceRoot / "LICENSE", "REFramework-LICENSE.txt")
        package.writestr(MANIFEST_NAME, json.dumps(info, ensure_ascii=False, indent=2).encode("utf-8"))
        package.writestr(INSTRUCTIONS_NAME, renderInstructions(info).encode("utf-8-sig"))
    return info


def verifyCorePackage(packagePath):
    with zipfile.ZipFile(packagePath) as package:
        if package.testzip() is not None:
            raise ValueError("汉化主包 ZIP 校验失败。")
        info = json.loads(package.read(MANIFEST_NAME))
        actualHash = hashlib.sha256(package.read("dinput8.dll")).hexdigest()
        if info["buildTarget"] != UNIVERSAL_TARGET or info["dllSha256"] != actualHash:
            raise ValueError("汉化 DLL 目标或校验值不一致。")
        if not info["officialReadmeGames"] or not package.read(INSTRUCTIONS_NAME):
            raise ValueError("汉化主包缺少游戏清单或安装说明。")
        return info


def fetchOfficialRelease(tag):
    parseNightlyTag(tag)
    headers = {"User-Agent": "REFramework-Chinese-Builder", "X-GitHub-Api-Version": API_VERSION}
    token = os.environ.get("GH_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = Request(f"{API_BASE}/repos/{OFFICIAL_REPOSITORY}/releases/tags/{tag}", headers=headers)
    with urlopen(request, timeout=REQUEST_TIMEOUT_SECONDS) as response:
        return json.load(response)


def downloadCompanions(release, destination):
    """只下载同一官方发布的两项可选附件，并核对官方 SHA256。"""
    tag = release["tag_name"]
    parseNightlyTag(tag)
    assetMap = {asset["name"]: asset for asset in release["assets"]}
    records = []
    for name in COMPANION_NAMES:
        asset = assetMap.get(name, {})
        digest = asset.get("digest", "")
        url = asset.get("browser_download_url", "")
        expectedUrl = f"https://github.com/{OFFICIAL_REPOSITORY}/releases/download/{tag}/{name}"
        if url != expectedUrl or re.fullmatch(r"sha256:[0-9a-f]{64}", digest) is None:
            raise ValueError(f"官方 {name} 缺少可信的同版本下载地址或校验值。")
        with urlopen(url, timeout=REQUEST_TIMEOUT_SECONDS) as response:
            content = response.read()
        actualHash = hashlib.sha256(content).hexdigest()
        if digest != f"sha256:{actualHash}":
            raise ValueError(f"官方 {name} 下载校验失败，已停止发布。")
        (destination / name).write_bytes(content)
        with zipfile.ZipFile(destination / name) as companion:
            if companion.testzip() is not None:
                raise ValueError(f"官方 {name} 不是有效 ZIP。")
        records.append({"name": name, "sha256": actualHash, "source": url, "localized": False})
    return records


def writeBundleMetadata(destination, info, records):
    hashes = "\n".join(f"{record['sha256']}  {record['name']}" for record in records)
    bundleHash = hashlib.sha256(hashes.encode("ascii")).hexdigest()
    infoPath = destination / BUNDLE_INFO_NAME
    bundleInfo = {
        "upstreamReleaseTag": info["upstreamReleaseTag"],
        "upstreamSourceSha": info["upstreamSourceSha"],
        "releaseTag": f"build-{bundleHash[:HASH_PREFIX_LENGTH]}",
        "files": records,
    }
    infoPath.write_text(json.dumps(bundleInfo, ensure_ascii=False, indent=2) + "\n", "utf-8")
    infoHash = hashlib.sha256(infoPath.read_bytes()).hexdigest()
    (destination / "SHA256SUMS.txt").write_text(hashes + f"\n{infoHash}  {BUNDLE_INFO_NAME}\n", "ascii")
    return bundleInfo


def writeReleaseNotes(destination, info):
    tag = info["upstreamReleaseTag"]
    notes = (
        "## 下载与安装\n\n"
        "- **REFramework.zip**：注入汉化库后重新编译的核心成品。普通使用只需将其中的 `dinput8.dll` 放到游戏程序目录。\n"
        "- **VR.zip**：同版本官方 VR 配套文件，仅 VR 用户需要，内容未做汉化修改。\n"
        "- **csharp-api.zip**：同版本官方 C# 插件框架，仅 C# 插件用户需要，普通 Lua 脚本无需安装。\n\n"
        "主包使用官方通用目标，在运行时识别游戏。游戏清单、安装说明和源码信息已放入主包。\n"
        "官方通用版不支持 RE2、RE3、RE7 的非光追旧版。汉化范围为框架与词库已收录的 Mod 界面，编译通过不代表逐游戏实测。\n\n"
        f"[对应官方发布](https://github.com/{OFFICIAL_REPOSITORY}/releases/tag/{tag})\n\n"
        f"Nightly 发布: {tag}\n{LAYOUT_MARKER}\n"
    )
    (destination / "release-notes.md").write_text(notes, "utf-8")


def prepareBundle(corePackage, outputDirectory, tag):
    info = verifyCorePackage(corePackage)
    if info["upstreamReleaseTag"] != tag or info["upstreamSourceSha"] != parseNightlyTag(tag)[1]:
        raise ValueError("汉化主包与配套包的官方版本不一致。")
    release = fetchOfficialRelease(tag)
    if release.get("tag_name") != tag or release.get("draft") or release.get("prerelease"):
        raise ValueError("官方发布状态或标签不符合本次构建。")
    if outputDirectory.exists():
        raise ValueError("发布输出目录已存在，请使用新的空目录。")
    outputDirectory.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=outputDirectory.parent) as temporary:
        destination = Path(temporary) / "bundle"
        destination.mkdir()
        shutil.copyfile(corePackage, destination / CORE_NAME)
        records = [{"name": CORE_NAME, "sha256": hashlib.sha256(corePackage.read_bytes()).hexdigest(), "localized": True}]
        records.extend(downloadCompanions(release, destination))
        bundleInfo = writeBundleMetadata(destination, info, records)
        writeReleaseNotes(destination, info)
        destination.rename(outputDirectory)
    return bundleInfo


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("core", type=Path)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--output", type=Path, default=Path("release"))
    args = parser.parse_args()
    info = prepareBundle(args.core, args.output, args.tag)
    print(f"发布包校验完成：{info['releaseTag']}，汉化核心包及两项同版本官方配套包。")


if __name__ == "__main__":
    main()
