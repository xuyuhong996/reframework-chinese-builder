"""生成本次发布的界面标识，并以独立补丁写入上游界面。"""

import json
import re
from pathlib import Path

LOCALIZATION_AUTHOR = "xuyuhong996"
LOCALIZATION_REPOSITORY_URL = "https://github.com/xuyuhong996/reframework-chinese-builder"
IDENTITY_HEADER_NAME = "LocalizationIdentity.hpp"
PATCH_MARKER = "/* REF_LOCALIZATION_IDENTITY */"
EXPECTED_MATCH_COUNT = 1
UPSTREAM_HEADER = '#include "CommitHash.autogenerated"'
UPSTREAM_TITLE = 'std::format("REFramework [{}+{}-{:.8}]", REF_TAG, REF_COMMITS_PAST_TAG, REF_COMMIT_HASH)'
LOCALIZED_TITLE = 'std::format("REFramework [Nightly {}]", REF_NIGHTLY_NUMBER)'
UPSTREAM_AUTHOR_LINE = '    ImGui::Text("Author: praydog");'
ABOUT_INSPIRATION_PATTERN = (
    r'^[ \t]*ImGui::Text\("(?:Inspired by the Kanan project\.|灵感来自Kanan项目。)"\);[ \t]*\n?'
)
LOCALIZED_ABOUT_LINES = (
    "    ImGui::TextUnformatted(REF_LOCALIZATION_AUTHOR);",
    '    reframework::localization::drawProjectLink("GitHub", REF_LOCALIZATION_PROJECT);',
)
LINK_HELPER = """
#include <windows.h>
#include <shellapi.h>
#include <imgui.h>
#ifdef _MSC_VER
#pragma comment(lib, "shell32.lib")
#endif

namespace reframework::localization {
    // 地址由构建脚本固定提供，点击后交给系统默认浏览器打开。
    inline void drawProjectLink(const char* label, const char* url) {
        if (ImGui::SmallButton(label)) {
            ShellExecuteA(nullptr, "open", url, nullptr, nullptr, SW_SHOWNORMAL);
        }
        ImGui::TextWrapped("%s", url);
    }
}
"""


def writeBuildIdentity(buildDirectory, nightlyNumber, projectUrl=None):
    """版本来自本次打包已确定的官方编号，不再单独请求最新版本。"""
    if not re.fullmatch(r"[0-9]{5}", nightlyNumber):
        raise ValueError("界面版本必须使用五位官方 Nightly 编号。")
    definitions = {
        "REF_NIGHTLY_NUMBER": nightlyNumber,
        "REF_LOCALIZATION_AUTHOR": f"汉化作者：{LOCALIZATION_AUTHOR}",
        "REF_LOCALIZATION_PROJECT": projectUrl or LOCALIZATION_REPOSITORY_URL,
    }
    lines = ["#pragma once", "// 由本次构建生成，界面编号与发布包保持一致。"]
    lines.extend(
        f"#define {name} {json.dumps(value, ensure_ascii=False)}" for name, value in definitions.items()
    )
    headerPath = Path(buildDirectory) / "src" / IDENTITY_HEADER_NAME
    headerPath.parent.mkdir(parents=True, exist_ok=True)
    headerPath.write_text("\n".join(lines) + "\n" + LINK_HELPER, encoding="utf-8")
    return headerPath


def replaceUnique(content, anchor, replacement):
    if content.count(anchor) != EXPECTED_MATCH_COUNT:
        raise ValueError(f"界面标识补丁的上游锚点缺失或重复：{anchor}")
    return content.replace(anchor, replacement, EXPECTED_MATCH_COUNT)


def removeAboutInspiration(content, required):
    """兼容首次构建与已有界面补丁，其他作者信息和许可证保持原样。"""
    patchedContent, matchCount = re.subn(ABOUT_INSPIRATION_PATTERN, "", content, flags=re.MULTILINE)
    if matchCount > EXPECTED_MATCH_COUNT or (required and matchCount != EXPECTED_MATCH_COUNT):
        raise ValueError("关于界面的文本锚点缺失或重复。")
    return patchedContent


def patchSourceIdentity(content):
    """全部锚点验证成功后才返回结果，重复执行不会重复插入。"""
    content = removeAboutInspiration(content, required=PATCH_MARKER not in content)
    if PATCH_MARKER in content:
        return content
    content = replaceUnique(
        content, UPSTREAM_HEADER, f'{UPSTREAM_HEADER}\n#include "{IDENTITY_HEADER_NAME}"\n{PATCH_MARKER}'
    )
    content = replaceUnique(content, UPSTREAM_TITLE, LOCALIZED_TITLE)
    aboutBlock = "\n".join((UPSTREAM_AUTHOR_LINE, *LOCALIZED_ABOUT_LINES))
    return replaceUnique(content, UPSTREAM_AUTHOR_LINE, aboutBlock)


def patchBuildIdentity(buildDirectory):
    sourcePath = Path(buildDirectory) / "src" / "REFramework.cpp"
    source = sourcePath.read_text("utf-8")
    patchedSource = patchSourceIdentity(source)
    if patchedSource != source:
        sourcePath.write_text(patchedSource, encoding="utf-8")
