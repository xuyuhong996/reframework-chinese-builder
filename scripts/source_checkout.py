"""获取已固定的上游提交，并在独立目录中构建，不清理维护者的源码。"""

import shutil
from datetime import datetime

from scripts.build_support import log, runCommand, writeText
from scripts.repository_identity import repositoryFromRemote
from scripts.upstream_release import SOURCE_REPOSITORY

SOURCE_TIMEOUT_SECONDS = 900


def initializeSource(sourceDirectory):
    if (sourceDirectory / ".git").exists():
        remote = runCommand(["git", "remote", "get-url", "origin"], sourceDirectory)
        if repositoryFromRemote(remote) != "praydog/REFramework":
            raise ValueError("源码目录指向其他仓库，请使用独立的 REFramework 源码目录。")
        if runCommand(["git", "status", "--porcelain", "--untracked-files=normal"], sourceDirectory):
            raise ValueError("上游源码目录存在本地修改，已保留；请先处理修改或指定其他源码目录。")
        return False
    if sourceDirectory.exists() and any(sourceDirectory.iterdir()):
        raise ValueError("源码目录非空且不是 Git 仓库，已保留原文件。")
    sourceDirectory.mkdir(parents=True, exist_ok=True)
    runCommand(["git", "init", "--quiet"], sourceDirectory)
    runCommand(["git", "remote", "add", "origin", SOURCE_REPOSITORY], sourceDirectory)
    return True


def checkoutSource(settings, release):
    source = settings.sourceDirectory
    created = initializeSource(source)
    try:
        currentSha = "" if created else runCommand(["git", "rev-parse", "--verify", "HEAD"], source)
    except RuntimeError:
        currentSha = ""
    if currentSha != release.sourceSha:
        runCommand(
            ["git", "fetch", "--depth", "1", "origin", release.sourceSha], source, SOURCE_TIMEOUT_SECONDS
        )
        runCommand(["git", "checkout", "--detach", release.sourceSha], source)
    runCommand(
        ["git", "submodule", "update", "--init", "--recursive", "--depth", "1"],
        source,
        SOURCE_TIMEOUT_SECONDS,
    )
    actualSha = runCommand(["git", "rev-parse", "HEAD"], source)
    if actualSha != release.sourceSha:
        raise ValueError("上游实际源码提交与本次 Nightly 不一致。")
    work = settings.workDirectory.resolve()
    if work == source.resolve() or work.is_relative_to(source.resolve()):
        raise ValueError("构建副本必须放在上游源码目录之外。")
    log(f"固定上游源码：{release.tag}")
    shutil.copytree(source, work, ignore=shutil.ignore_patterns(".git", "build", "build_*"))
    return work


def writeCommitIdentity(settings, release):
    now = datetime.now()
    definitions = {
        "REF_COMMIT_HASH": f'"{release.sourceSha}"',
        "REF_TAG": f'"{release.tag}"',
        "REF_TAG_LONG": f'"{release.tag}"',
        "REF_COMMITS_PAST_TAG": "0",
        "REF_BRANCH": '"HEAD"',
        "REF_TOTAL_COMMITS": "0",
        "REF_BUILD_DATE": f'"{now:%d.%m.%Y}"',
        "REF_BUILD_TIME": f'"{now:%H:%M}"',
    }
    content = "#pragma once\n" + "".join(f"#define {key} {value}\n" for key, value in definitions.items())
    destination = settings.workDirectory / "src/CommitHash.autogenerated"
    destination.parent.mkdir(parents=True, exist_ok=True)
    writeText(destination, content)
