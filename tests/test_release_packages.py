"""验证同版本汉化主包、官方配套包及发布失败时的成品保护。"""

import hashlib
import io
import json
import os
import tempfile
import unittest
import zipfile
from pathlib import Path
from unittest.mock import patch

from scripts import release_packages as packages

SOURCE_SHA = "d4611aef1d63effd3a736bdf9404ea702428017d"
NIGHTLY_TAG = f"nightly-01433-{SOURCE_SHA}"
GAMES = ["Resident Evil 4", "Devil May Cry 5", "Monster Hunter Wilds"]
DLL_BYTES = b"test-only-core-dll"


def makeCompanion(name):
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as package:
        package.writestr("optional-component.txt", name)
    return output.getvalue()


class ReleasePackageTests(unittest.TestCase):
    def setUp(self):
        temporaryDirectory = tempfile.TemporaryDirectory()
        self.addCleanup(temporaryDirectory.cleanup)
        self.root = Path(temporaryDirectory.name)
        self.sourceRoot = self.root / "source"
        (self.sourceRoot / "src").mkdir(parents=True)
        self.writeSource()
        self.dllPath = self.root / "dinput8.dll"
        self.dllPath.write_bytes(DLL_BYTES)
        self.qrPath = self.root / "reward.jpg"
        self.qrPath.write_bytes(b"existing-reward")
        self.corePath = self.root / "core.zip"
        self.outputPath = self.root / "release"
        self.files = packages.CoreFiles(self.sourceRoot, self.dllPath, self.corePath, self.qrPath)
        self.environment = patch.dict(os.environ, {
            "UPSTREAM_RELEASE_TAG": NIGHTLY_TAG, "UPSTREAM_SHA": SOURCE_SHA,
        }, clear=True)
        self.environment.start()
        self.addCleanup(self.environment.stop)
        self.companions = {name: makeCompanion(name) for name in packages.COMPANION_NAMES}
        self.release = {"tag_name": NIGHTLY_TAG, "draft": False, "prerelease": False, "assets": [
            {"name": name, "digest": f"sha256:{hashlib.sha256(content).hexdigest()}",
             "browser_download_url": f"https://github.com/{packages.OFFICIAL_REPOSITORY}/releases/download/{NIGHTLY_TAG}/{name}"}
            for name, content in self.companions.items()
        ]}

    def writeSource(self):
        (self.sourceRoot / "README.md").write_text(
            "# Official\n## Supported Games\n" + "\n".join(f"* {game}" for game in GAMES), "utf-8"
        )
        (self.sourceRoot / "LICENSE").write_text("Official license fixture", "utf-8")
        (self.sourceRoot / "src/CommitHash.autogenerated").write_text(
            f'#define REF_COMMIT_HASH "{SOURCE_SHA}"\n', "utf-8"
        )
        (self.sourceRoot / "cmake.toml").write_text(
            '[target.REFramework]\ncompile-definitions = ["REFRAMEWORK_UNIVERSAL"]\n'
            '[target.REFrameworkSDK]\ncompile-definitions = ["REFRAMEWORK_UNIVERSAL"]\n', "utf-8"
        )
        (self.sourceRoot / "CMakeLists.txt").write_text(
            'add_library(REFramework SHARED)\n'
            'target_compile_definitions(REFramework PUBLIC\n REFRAMEWORK_UNIVERSAL\n)\n'
            'target_compile_definitions(REFrameworkSDK PUBLIC\n REFRAMEWORK_UNIVERSAL\n)\n', "utf-8"
        )

    def openDownload(self, url, timeout):
        self.assertEqual(timeout, packages.REQUEST_TIMEOUT_SECONDS)
        return io.BytesIO(self.companions[url.rsplit("/", 1)[1]])

    def prepareBundle(self):
        with (
            patch.object(packages, "fetchOfficialRelease", return_value=self.release),
            patch.object(packages, "urlopen", side_effect=self.openDownload),
        ):
            return packages.prepareBundle(self.corePath, self.outputPath, NIGHTLY_TAG)

    def testBundleKeepsLocalizedCoreAndOriginalMatchingCompanions(self):
        packages.createCorePackage(self.files)
        info = self.prepareBundle()
        self.assertEqual({record["name"] for record in info["files"]}, {
            packages.CORE_NAME, *packages.COMPANION_NAMES,
        })
        self.assertEqual([record["localized"] for record in info["files"]], [True, False, False])
        for name, content in self.companions.items():
            self.assertEqual((self.outputPath / name).read_bytes(), content)
        with zipfile.ZipFile(self.outputPath / packages.CORE_NAME) as core:
            self.assertEqual(core.read("dinput8.dll"), DLL_BYTES)
            manifest = json.loads(core.read(packages.MANIFEST_NAME))
            self.assertEqual(manifest["officialReadmeGames"], GAMES)
            self.assertIn("不代表", manifest["verification"])
            self.assertIn("VR.zip", core.read(packages.INSTRUCTIONS_NAME).decode("utf-8-sig"))
        checksums = (self.outputPath / "SHA256SUMS.txt").read_text("ascii").splitlines()
        for checksumLine in checksums:
            expectedHash, name = checksumLine.split("  ")
            self.assertEqual(hashlib.sha256((self.outputPath / name).read_bytes()).hexdigest(), expectedHash)

    def testNewOfficialGameIsAutomaticallyIncluded(self):
        with (self.sourceRoot / "README.md").open("a", encoding="utf-8") as readme:
            readme.write("\n* Another officially listed game\n")
        packages.createCorePackage(self.files)
        info = packages.verifyCorePackage(self.corePath)
        self.assertEqual(info["officialReadmeGames"], GAMES + ["Another officially listed game"])

    def testSourceMismatchAndLegacyTargetCannotOverwriteExistingCore(self):
        self.corePath.write_bytes(b"previous-core")
        with (
            patch.dict(os.environ, {"UPSTREAM_SHA": "wrong-source"}),
            self.assertRaisesRegex(ValueError, "不一致"),
        ):
            packages.createCorePackage(self.files)
        cmake = self.sourceRoot / "CMakeLists.txt"
        cmake.write_text(cmake.read_text("utf-8").replace("REFRAMEWORK_UNIVERSAL", "MHWILDS"), "utf-8")
        with self.assertRaisesRegex(ValueError, "通用"):
            packages.createCorePackage(self.files)
        self.assertEqual(self.corePath.read_bytes(), b"previous-core")

    def testWrongOfficialVersionDoesNotCreateRelease(self):
        packages.createCorePackage(self.files)
        self.release["tag_name"] = "nightly-01432-" + SOURCE_SHA
        with self.assertRaisesRegex(ValueError, "标签"):
            self.prepareBundle()
        self.assertFalse(self.outputPath.exists())

    def testDamagedCompanionDoesNotCreateReleaseOrChangeCore(self):
        packages.createCorePackage(self.files)
        originalCore = self.corePath.read_bytes()
        self.companions["VR.zip"] = b"damaged-download"
        with self.assertRaisesRegex(ValueError, "校验失败"):
            self.prepareBundle()
        self.assertFalse(self.outputPath.exists())
        self.assertEqual(self.corePath.read_bytes(), originalCore)

    def testMissingOfficialChecksumOrAssetIsRejected(self):
        packages.createCorePackage(self.files)
        self.release["assets"][0]["digest"] = ""
        with self.assertRaisesRegex(ValueError, "校验值"):
            self.prepareBundle()
        self.release["assets"] = []
        with self.assertRaisesRegex(ValueError, "校验值"):
            self.prepareBundle()
        self.assertFalse(self.outputPath.exists())

    def testChangedCoreIsRejectedBeforeNetworkAccess(self):
        packages.createCorePackage(self.files)
        with zipfile.ZipFile(self.corePath) as core:
            contents = {name: core.read(name) for name in core.namelist()}
        contents["dinput8.dll"] = b"different-dll"
        with zipfile.ZipFile(self.corePath, "w") as core:
            for name, content in contents.items():
                core.writestr(name, content)
        with patch.object(packages, "fetchOfficialRelease") as fetchRelease:
            with self.assertRaisesRegex(ValueError, "校验值"):
                packages.prepareBundle(self.corePath, self.outputPath, NIGHTLY_TAG)
            fetchRelease.assert_not_called()


if __name__ == "__main__":
    unittest.main()
