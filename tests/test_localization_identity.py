"""验证界面编号与发布包绑定、项目署名及上游界面补丁边界。"""

import tempfile
import unittest
from pathlib import Path

from scripts import localization_identity as identity
from scripts.nexus_links import loadNexusPages

NIGHTLY_NUMBER = "01436"
UPSTREAM_SOURCE = """#include "CommitHash.autogenerated"
static const auto REF_NAME = std::format("REFramework [{}+{}-{:.8}]", REF_TAG, REF_COMMITS_PAST_TAG, REF_COMMIT_HASH);
void drawAbout() {
    ImGui::Text("Author: praydog");
    ImGui::Text("Inspired by the Kanan project.");
    ImGui::Text("https://github.com/praydog/REFramework");
    ImGui::Text("http://praydog.com");
    ImGui::TreeNode("Licenses");
}
"""


class LocalizationIdentityTests(unittest.TestCase):
    def testHeaderUsesTheSameNightlyNumberAndProjectIdentity(self):
        with tempfile.TemporaryDirectory() as directory:
            headerPath = identity.writeBuildIdentity(directory, NIGHTLY_NUMBER)
            header = headerPath.read_text("utf-8")
        self.assertIn(f'#define REF_NIGHTLY_NUMBER "{NIGHTLY_NUMBER}"', header)
        self.assertIn(f"汉化作者：{identity.LOCALIZATION_AUTHOR}", header)
        self.assertIn(identity.LOCALIZATION_REPOSITORY_URL, header)
        for url in loadNexusPages().values():
            self.assertIn(url, header)

    def testInvalidNightlyNumbersDoNotCreateAHeader(self):
        for invalidNumber in ("", "1436", "001436", "０１４３６", "01436\n", "../01436"):
            with self.subTest(number=invalidNumber), tempfile.TemporaryDirectory() as directory:
                with self.assertRaises(ValueError):
                    identity.writeBuildIdentity(directory, invalidNumber)
                self.assertEqual(list(Path(directory).iterdir()), [])

    def testWindowUsesOfficialNightlyInsteadOfGitHistoryDescription(self):
        patchedSource = identity.patchSourceIdentity(UPSTREAM_SOURCE)
        self.assertIn(identity.LOCALIZED_TITLE, patchedSource)
        self.assertNotIn(identity.UPSTREAM_TITLE, patchedSource)
        self.assertIn(f'#include "{identity.IDENTITY_HEADER_NAME}"', patchedSource)

    def testProjectIdentityKeepsOriginalCreditsAndLicenses(self):
        patchedSource = identity.patchSourceIdentity(UPSTREAM_SOURCE)
        self.assertIn(identity.UPSTREAM_AUTHOR_LINE, patchedSource)
        self.assertNotIn('ImGui::Text("Inspired by the Kanan project.");', patchedSource)
        self.assertIn('ImGui::Text("https://github.com/praydog/REFramework");', patchedSource)
        self.assertIn('ImGui::TreeNode("Licenses");', patchedSource)
        for aboutLine in identity.LOCALIZED_ABOUT_LINES:
            self.assertIn(aboutLine, patchedSource)

    def testReapplyingThePatchDoesNotDuplicateProjectInfo(self):
        patchedSource = identity.patchSourceIdentity(UPSTREAM_SOURCE)
        self.assertEqual(identity.patchSourceIdentity(patchedSource), patchedSource)
        self.assertEqual(patchedSource.count(identity.PATCH_MARKER), identity.EXPECTED_MATCH_COUNT)

    def testExistingPatchedSourcesRemoveBothOriginalAndTranslatedAboutText(self):
        patchedSource = identity.patchSourceIdentity(UPSTREAM_SOURCE)
        for text in ("Inspired by the Kanan project.", "灵感来自Kanan项目。"):
            with self.subTest(text=text):
                legacySource = patchedSource.replace(
                    identity.UPSTREAM_AUTHOR_LINE,
                    f'{identity.UPSTREAM_AUTHOR_LINE}\n    ImGui::Text("{text}");',
                )
                self.assertEqual(identity.patchSourceIdentity(legacySource), patchedSource)

    def testExistingNexusLinkIsMigratedToTheGameSelector(self):
        patchedSource = identity.patchSourceIdentity(UPSTREAM_SOURCE)
        legacySource = patchedSource.replace(identity.LOCALIZED_ABOUT_LINES[-1], identity.LEGACY_NEXUS_LINK)
        self.assertEqual(identity.patchSourceIdentity(legacySource), patchedSource)
        self.assertNotIn("REF_LOCALIZATION_NEXUS", patchedSource)

    def testUpstreamDriftFailsWithoutPartiallyWritingTheSource(self):
        anchors = (
            identity.UPSTREAM_HEADER,
            identity.UPSTREAM_TITLE,
            identity.UPSTREAM_AUTHOR_LINE,
            '    ImGui::Text("Inspired by the Kanan project.");',
        )
        for anchor in anchors:
            with self.subTest(anchor=anchor), tempfile.TemporaryDirectory() as directory:
                sourcePath = Path(directory) / "src" / "REFramework.cpp"
                sourcePath.parent.mkdir()
                source = UPSTREAM_SOURCE.replace(anchor, "")
                sourcePath.write_text(source, "utf-8")
                with self.assertRaises(ValueError):
                    identity.patchBuildIdentity(directory)
                self.assertEqual(sourcePath.read_text("utf-8"), source)


if __name__ == "__main__":
    unittest.main()
